#!/usr/bin/env python3
"""
A simple Python script to demonstrate code storage on GitHub.
This is just an example - you can store any programming language!
"""

def greet(name):
    """Greet someone by name."""
    return f"Hello, {name}! Welcome to GitHub!"

def main():
    """Main function."""
    print(greet("World"))
    print("\nThis is a simple example showing:")
    print("- How to store code on GitHub")
    print("- How to organize your projects")
    print("- How to track changes over time")

if __name__ == "__main__":
    main()
